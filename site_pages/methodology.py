import streamlit as st

st.title("Methodology")
st.write("This section discusses the setup and methods used for this project.")

st.header("The Setup")
st.write("**Three regression models** were implemented from scratch, each model predicts the **power generated** by every fuel " \
         "source from the year. The data was subjected to a **80/20 split**: the first 24 years serves as training data, and the " \
         "latter 7 were used for testing.")
st.write("The following **hyperparameters** were used for the regression models:")

# some info
c1, c2, c3, c4 = st.columns(4)
c1.metric("Iterations", "10000")
c2.metric("Learning rate", "0.001")
c3.metric("Train / Test split (%)", "80 / 20")
c4.metric("Years", "2021 to 2030")

st.header("Regression Models")

tab_linear, tab_poly, tab_ridge = st.tabs(["Linear", "Polynomial", "Ridge"])

with tab_linear:
    st.markdown("### Linear Regression")
    
    with st.container(border = True):
        st.markdown("""
                **Linear regression** fits a straight line that relates
                the year to the power generated by each fuel source, 
                where the **weight w** represents the yearly rate of change and the 
                **bias b** represents the starting value.
                The model was implemented using gradient descent: ~10000 iterations, 
                the prediction error is computed and the weights and bias are 
                squared error. The years were standardized using the training mean and standard 
                deviation, and negative predictions were clipped to zero since power generation 
                cannot be negative.
        """)

with tab_poly:
    st.markdown("### Polynomial Regression")

    with st.container(border = True):
        st.markdown("""
                **Polynomial regression** extends the linear model 
                so that it can follow **curved trends**, 
                by expanding each year into the features **x, x², x³, and x⁴** (degree 4).
                A feature matrix was constructed by raising the standardized year to each power,
                and the same gradient-descent procedure then learns one weight for each power in addition to a bias.
                Because higher power grows rapidly, standardizing the years beforehand is necessary for stable training,
                and negative predictions were clipped to zero.
        """)

with tab_ridge:
    st.markdown("### Ridge Regression")
    
    with st.container(border = True):
        st.markdown("""
                **Ridge regression** is similar to linear, though it imposes a **penalty on larger weights**. It
                fits the same line for each fuel source, with a **weight w** and **bias b** and is also trained
                with the same gradient-descent process. The difference is that whenever each weight is updated,
                **α** (which is 1 in this case) scales a term proportional to the weight, which is added to
                the gradient and pulls it towards zero.
        """)


